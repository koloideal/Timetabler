from typing import Protocol

from timetabler.domain.schemas import PublishReport, Revision


class CreatorNotifier(Protocol):
    async def ask_revision_approval(self, revision: Revision) -> None: ...

    async def notify_revision_report(self, report: PublishReport) -> None: ...

    async def notify_error(self, title: str, details: str = "") -> None: ...

    async def notify_creator(self, text: str) -> None: ...
